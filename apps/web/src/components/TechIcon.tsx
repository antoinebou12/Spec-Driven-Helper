/** Brand mark when available (Simple Icons, CC0), otherwise a category icon. Decorative. */
export function TechIcon({ technology, size = 18 }: { technology: Pick<Technology, 'icon' | 'category'>; size?: number }) {
  const brand = technology.icon ? brands[technology.icon] : undefined;
  if (brand) {
    const [r, g, b] = [0, 2, 4].map((i) => parseInt(brand.hex.slice(i, i + 2), 16) / 255);
    const dim = 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.25;
    return (
      <svg className={`tech-icon${dim ? ' dim' : ''}`} width={size} height={size} viewBox="0 0 24 24" aria-hidden="true" style={{ color: `#${brand.hex}` }}>
        <path d={brand.path} fill="currentColor" />
      </svg>
    );
  }
  const Icon = categoryIcons[technology.category] ?? Wrench;
  return <Icon className="tech-icon" size={size} aria-hidden />;
}
