/**
 * Smoke test for the nginx web image (docker/web.Dockerfile): builds it, runs it against a stub
 * API on the host and checks health, security headers, caching, SPA deep links and the /api proxy.
 * Usage: pnpm smoke:web [--skip-build]. Needs Docker.
 */
import { execFileSync } from 'node:child_process';
import { createServer } from 'node:http';
import type { AddressInfo } from 'node:net';

const image = 'sdd-studio-web:smoke';
const name = `sdd-web-smoke-${process.pid}`;
const port = Number(process.env.SMOKE_WEB_PORT ?? 18080);
const docker = (...args: string[]) => execFileSync('docker', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }).trim();

const failures: string[] = [];
function check(label: string, ok: boolean, detail = '') {
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${label}${ok || !detail ? '' : ` — ${detail}`}`);
  if (!ok) failures.push(label);
}

async function waitFor(url: string, timeoutMs = 30_000) {
  const until = Date.now() + timeoutMs;
  while (Date.now() < until) {
    try {
      if ((await fetch(url)).ok) return;
    } catch {
      /* not up yet */
    }
    await new Promise((r) => setTimeout(r, 500));
  }
  throw new Error(`${url} did not become ready`);
}

async function main() {
  if (!process.argv.includes('--skip-build')) {
    console.log(`Building ${image}…`);
    execFileSync('docker', ['build', '-f', 'docker/web.Dockerfile', '-t', image, '.'], { stdio: 'inherit' });
  }
  const seen: { url?: string; proto?: string }[] = [];
  const api = createServer((req, res) => {
    seen.push({ url: req.url, proto: req.headers['x-forwarded-proto'] as string | undefined });
    res.writeHead(200, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ status: 'stub', path: req.url }));
  });
  await new Promise<void>((resolve) => api.listen(0, '0.0.0.0', resolve));
  const apiPort = (api.address() as AddressInfo).port;
  docker(
    'run', '-d', '--rm', '--name', name,
    '--add-host', 'host.docker.internal:host-gateway',
    '-e', `API_UPSTREAM=http://host.docker.internal:${apiPort}`,
    '-p', `127.0.0.1:${port}:8080`,
    image,
  );
  const base = `http://127.0.0.1:${port}`;
  try {
    await waitFor(`${base}/healthz`);
    const health = await fetch(`${base}/healthz`);
    check('health endpoint answers 200', health.status === 200 && (await health.text()).trim() === 'ok');

    const shell = await fetch(`${base}/`);
    const html = await shell.text();
    check('shell is served', shell.status === 200 && html.includes('<div id="root">'), `status ${shell.status}`);
    check('shell is not cached', shell.headers.get('cache-control') === 'no-cache', String(shell.headers.get('cache-control')));
    const csp = shell.headers.get('content-security-policy') ?? '';
    check('CSP forbids framing and foreign scripts', csp.includes("frame-ancestors 'none'") && csp.includes("script-src 'self'") && csp.includes("object-src 'none'"), csp);
    check('nosniff, referrer and frame headers', shell.headers.get('x-content-type-options') === 'nosniff' && shell.headers.get('referrer-policy') === 'same-origin' && shell.headers.get('x-frame-options') === 'DENY');
    check('server version hidden', !/\d/.test(shell.headers.get('server') ?? ''), String(shell.headers.get('server')));

    const deep = await fetch(`${base}/projects/demo/board?card=1`);
    check('deep links fall back to the shell', deep.status === 200 && (await deep.text()) === html);

    const asset = /src="(\/assets\/[^"]+\.js)"/.exec(html)?.[1];
    check('shell references a hashed script', !!asset);
    if (asset) {
      const js = await fetch(`${base}${asset}`);
      check('hashed assets are immutable', js.status === 200 && (js.headers.get('cache-control') ?? '').includes('immutable'), String(js.headers.get('cache-control')));
      check('assets keep security headers', js.headers.get('x-content-type-options') === 'nosniff');
      check('assets are gzip-compressed', js.headers.get('content-encoding') === 'gzip', String(js.headers.get('content-encoding')));
    }
    const missing = await fetch(`${base}/assets/does-not-exist.js`);
    check('missing assets are 404, not the shell', missing.status === 404, `status ${missing.status}`);

    const proxied = await fetch(`${base}/api/v1/health?probe=1`);
    const body = (await proxied.json().catch(() => ({}))) as { status?: string; path?: string };
    check('/api is proxied to the backend', proxied.status === 200 && body.status === 'stub' && body.path === '/api/v1/health?probe=1', JSON.stringify(body));
    check('proxy forwards the scheme', seen.some((s) => s.proto === 'http'));
    // AI-optimisation files are generated by the API, not served as the shell.
    for (const path of ['/llms.txt', '/llms-full.txt', '/robots.txt', '/sitemap.xml']) {
      const file = (await (await fetch(`${base}${path}`)).json().catch(() => ({}))) as { path?: string };
      check(`${path} is proxied to the backend`, file.path === path, JSON.stringify(file));
    }
    const docs = await fetch(`${base}/docs/`);
    const docsHtml = await docs.text();
    check('documentation website is served at /docs/', docs.status === 200 && docsHtml.includes('SDD Studio docs') && docsHtml.includes('search.js'), `status ${docs.status}`);
    const shellHtml = await (await fetch(`${base}/`)).text();
    check('shell carries JSON-LD and a no-JavaScript summary', shellHtml.includes('application/ld+json') && shellHtml.includes('<noscript>'));
  } finally {
    if (failures.length)
      try {
        console.log(docker('logs', name));
      } catch {
        /* container already gone */
      }
    try {
      docker('stop', name);
    } catch {
      /* already stopped */
    }
    api.close();
  }
  if (failures.length) {
    console.error(`\n${failures.length} check(s) failed.`);
    process.exit(1);
  }
  console.log('\nWeb image smoke test passed.');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
