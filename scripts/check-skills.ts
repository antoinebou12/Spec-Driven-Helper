/**
 * Audits agent skills against Anthropic's skill authoring best practices
 * (https://platform.claude.com/docs/en/agents-and-tools/agent-skills/best-practices).
 *
 *   pnpm skills:check                    this repository's skills, the skills SDD Studio generates, and the
 *                                        .claude / .agents copies being identical
 *   pnpm skills:check <folder> [...]     any skill folder, or a folder of skills (for example ~/.claude/skills)
 *   pnpm skills:check --strict           warnings fail too (CI uses this for the repository's own skills)
 *
 * Errors break a documented rule or make a skill hard to use; warnings are advice.
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { buildExampleSpec } from '../packages/shared/src/example';
import { createSpec } from '../packages/shared/src/domain';
import { auditSkills, repositorySkills, skillsIn, type SkillFiles, type SkillFinding } from '../packages/shared/src/skill-audit';
import { agentFiles, skillFiles } from '../apps/api/src/exports';

const { values, positionals } = parseArgs({ options: { strict: { type: 'boolean', default: false } }, allowPositionals: true });
const root = resolve(import.meta.dirname, '..');
const textFile = /\.(?:md|mdx|txt|json|ya?ml|toml|py|js|mjs|cjs|ts|sh|ps1|csv|html|css)$/i;
const skipped = new Set(['node_modules', '.git', '__pycache__']);

/** A folder's text files keyed by path below `base`, with the folder's own name as the first segment. */
function readTree(folder: string, base = basename(folder)): SkillFiles {
  const files: SkillFiles = {};
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    if (skipped.has(entry.name)) continue;
    const path = join(folder, entry.name);
    if (entry.isDirectory()) Object.assign(files, readTree(path, `${base}/${entry.name}`));
    else if (textFile.test(entry.name)) files[`${base}/${entry.name}`] = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
  }
  return files;
}

const findings: SkillFinding[] = [];
const audited: string[] = [];
const run = (label: string, files: SkillFiles) => {
  for (const { dir } of skillsIn(files)) audited.push(`${label}${dir}`);
  findings.push(...auditSkills(files).map((f) => ({ ...f, file: `${label}${f.file}` })));
};

if (positionals.length) {
  for (const target of positionals) {
    const folder = resolve(target);
    if (!existsSync(folder) || !statSync(folder).isDirectory()) {
      console.error(`FAIL  ${target} is not a folder`);
      process.exit(1);
    }
    const files = readTree(folder);
    if (!skillsIn(files).length) {
      console.error(`FAIL  no SKILL.md found under ${target}`);
      process.exit(1);
    }
    run('', files);
  }
} else {
  // Skills another tool generates (OpenSpec's) are rewritten by that tool and differ per agent on purpose: listed, not checked.
  const generated = new Set<string>();
  const trees = Object.fromEntries(
    ['.claude/skills', '.agents/skills']
      .filter((d) => existsSync(join(root, d)))
      .map((d) => {
        const own = repositorySkills(readTree(join(root, d), d));
        own.generated.forEach((dir) => generated.add(dir.split('/').pop()!));
        return [d, own.files];
      }),
  );
  for (const files of Object.values(trees)) run('', files);
  if (generated.size) console.log(`skip  ${generated.size} skills generated by another tool (${[...generated].sort().join(', ')}); refresh them with that tool, not by hand`);
  // The two folders hold the same skills for two tools; they must not drift apart.
  const [claude, agents] = ['.claude/skills', '.agents/skills'].map((d) => trees[d] ?? {});
  for (const path of new Set([...Object.keys(claude).map((p) => p.slice('.claude/skills/'.length)), ...Object.keys(agents).map((p) => p.slice('.agents/skills/'.length))])) {
    const a = claude[`.claude/skills/${path}`];
    const b = agents[`.agents/skills/${path}`];
    if (a === b) continue;
    findings.push({ severity: 'error', rule: 'copies-differ', file: path, message: a === undefined ? 'Only in .agents/skills; keep it identical to .claude/skills.' : b === undefined ? 'Only in .claude/skills; keep it identical to .agents/skills.' : '.claude/skills and .agents/skills hold different versions; copy the newer one over the other.' });
  }
  // What SDD Studio writes for every project is a product feature, so it is held to the same rules.
  const id = '00000000-0000-4000-8000-0000000000f1';
  run('generated: ', skillFiles(buildExampleSpec(id)));
  run('generated: ', skillFiles(createSpec(id.replace(/1$/, '2'), 'Claude <b>Helper</b>', 'en', false, 'Web application')));
  run('generated: ', agentFiles(buildExampleSpec(id)));
}

const errors = findings.filter((f) => f.severity === 'error');
const warnings = findings.filter((f) => f.severity === 'warning');
for (const f of findings) console.log(`${f.severity === 'error' ? 'ERROR' : 'warn '} ${f.rule.padEnd(18)} ${f.file}\n      ${f.message}`);
console.log(`${errors.length || (values.strict && warnings.length) ? 'FAIL ' : 'ok   '} ${audited.length} skills checked: ${errors.length} errors, ${warnings.length} warnings${values.strict ? ' (strict)' : ''}`);
if (!audited.length) {
  console.error('FAIL  no skills found');
  process.exit(1);
}
process.exit(errors.length || (values.strict && warnings.length) ? 1 : 0);
