import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { projectGraph } from 'archunit';

/**
 * Writes the module dependency graph with ArchUnitTS: a folder-level Mermaid diagram for the docs
 * and an interactive file-level HTML report. Usage: pnpm arch:graph [output folder].
 */
const out = process.argv[2] ?? 'docs/architecture';
await mkdir(out, { recursive: true });

const folders = projectGraph()
  .collapseByPattern(/^(apps\/[\w-]+|packages\/[\w-]+|scripts|tests)\/.*$/, '$1')
  .titled('SDD Studio module dependencies');
const mermaid = await folders.toMermaid();
await writeFile(
  join(out, 'dependencies.md'),
  `# Module dependencies\n\nGenerated by \`pnpm arch:graph\` (ArchUnitTS). Edge labels count file-level imports.\n\n\`\`\`mermaid\n${mermaid.trim()}\n\`\`\`\n`,
);
await projectGraph().titled('SDD Studio file dependencies').exportAsHTML(join(out, 'dependencies.html'));
console.log(`Wrote ${join(out, 'dependencies.md')} and ${join(out, 'dependencies.html')}`);
