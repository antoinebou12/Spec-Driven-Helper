import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * One folder per task in .plan/tasks/TASK-###/ with intent.md (why, for whom, what it delivers) and
 * spec.md (scope, acceptance, verification, history). Built only from the plan's own records:
 * tasks.md (status, title, notes, area), expanded-scope.md (scope), browser-review.md (acceptance and
 * verification) and changes.md (history). Nothing is invented: missing acceptance criteria are shown
 * as missing. Files whose first line is not the generated marker are hand-edited and left alone.
 *
 * `pnpm plan:tasks` writes; `pnpm plan:tasks:check` fails when a generated file is out of date.
 */
const plan = '.plan';
export const marker = '<!-- Generated by scripts/plan-task-docs.ts from the .plan records. Delete this line to edit by hand; it will then be kept. -->';
const check = process.argv.includes('--check');

export type PlanTask = { id: string; status: 'done' | 'in-progress' | 'pending'; title: string; notes: string; area: string };

export function parseTasks(markdown: string): PlanTask[] {
  const out: PlanTask[] = [];
  let area = '';
  for (const line of markdown.split(/\r?\n/)) {
    const heading = /^##\s+(.+)$/.exec(line);
    if (heading) area = heading[1].trim();
    const m = /^- \[([ x/])\] (TASK-\d+)\s+(.*)$/.exec(line);
    if (!m) continue;
    const body = m[3];
    const notes = /\s_(.+)_\s*$/.exec(body)?.[1] ?? '';
    const title = (notes ? body.slice(0, body.lastIndexOf(` _${notes}_`)) : body).trim();
    out.push({ id: m[2], status: m[1] === 'x' ? 'done' : m[1] === '/' ? 'in-progress' : 'pending', title, notes, area });
  }
  return out;
}

/** `- **TASK-060** text` entries of expanded-scope.md. */
export function parseScope(markdown: string) {
  return new Map([...markdown.matchAll(/^- \*\*(TASK-\d+)\*\*\s+(.+)$/gm)].map((m) => [m[1], m[2].trim()]));
}

/** `| 128 | acceptance | verification |` rows of browser-review.md. */
export function parseReview(markdown: string) {
  return new Map(
    [...markdown.matchAll(/^\|\s*(\d{3})\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*$/gm)].map((m) => [`TASK-${m[1]}`, { acceptance: m[2], verification: m[3] }]),
  );
}

/** Change entries (`## date — CHG-### title`) that mention each task, including ranges like TASK-128 through TASK-135. */
export function parseChanges(markdown: string) {
  const byTask = new Map<string, string[]>();
  const sections = markdown.split(/^(?=## )/m).filter((s) => s.startsWith('## '));
  for (const section of sections) {
    const heading = section.split(/\r?\n/)[0].replace(/^##\s+/, '').trim();
    const ids = new Set(section.match(/TASK-\d+/g) ?? []);
    for (const r of section.matchAll(/TASK-(\d+)\s*(?:through|to|–|-)\s*(?:TASK-)?(\d+)/g))
      for (let n = Number(r[1]); n <= Number(r[2]) && n - Number(r[1]) < 100; n++) ids.add(`TASK-${String(n).padStart(3, '0')}`);
    for (const r of section.matchAll(/TASK-(\d+),\s*(\d{3})(?:,\s*(\d{3}))*/g)) for (const n of r[0].match(/\d{3}/g) ?? []) ids.add(`TASK-${n}`);
    for (const id of ids) byTask.set(id, [...(byTask.get(id) ?? []), heading]);
  }
  return byTask;
}

const statusText = { done: 'Done — implemented and verified', 'in-progress': 'In progress — implemented, verification incomplete', pending: 'Pending' } as const;
const sentence = (s: string) => (s && !/[.!?]$/.test(s) ? `${s}.` : s);
/** Files and commands named in a text, as verification evidence. */
const evidence = (text: string) =>
  [...new Set(text.match(/`[^`]+`|\b[\w./-]+\.(?:test|spec)\.tsx?\b|\b[\w-]+\.stories\.tsx\b/g) ?? [])]
    .map((e) => e.replace(/^`|`$/g, ''))
    .filter((e) => /^pnpm |^act |\.(test|spec)\.tsx?$|\.stories\.tsx$|^tests\//.test(e));

export function taskDocs(task: PlanTask, scope?: string, review?: { acceptance: string; verification: string }, changes: string[] = []) {
  const name = task.title.split(/[:.](?:\s|$)/)[0].trim();
  const outcome =
    task.status === 'pending'
      ? 'Not delivered yet.'
      : task.notes
        ? sentence(task.notes)
        : 'Delivered as described in the scope; no further notes were recorded.';
  const intent = [
    marker,
    `# ${task.id} — ${name}`,
    '',
    `- **Status:** ${statusText[task.status]}`,
    `- **Area:** ${task.area || 'Unassigned'}`,
    '',
    '## Intent',
    '',
    sentence(scope ?? task.title),
    '',
    '## What it delivers',
    '',
    outcome,
    '',
    '## History',
    '',
    ...(changes.length ? changes.map((c) => `- ${c}`) : ['- No change entry mentions this task yet.']),
    '',
  ].join('\n');
  const acceptance = review
    ? [`- [${task.status === 'done' ? 'x' : ' '}] ${sentence(review.acceptance.trim())}`]
    : scope
      ? scope
          .split(/(?<=\.)\s+(?=[A-Z])/)
          .filter((s) => !/^Updated \d{4}/.test(s))
          .map((s) => `- [${task.status === 'done' ? 'x' : ' '}] ${sentence(s.trim())}`)
      : ['- Not recorded. Add acceptance criteria here before changing this task.'];
  const verified = review ? [review.verification] : evidence(task.notes);
  const spec = [
    marker,
    `# ${task.id} — specification`,
    '',
    '## Scope',
    '',
    sentence(task.title),
    '',
    '## Acceptance criteria',
    '',
    ...acceptance,
    '',
    '## Verification',
    '',
    ...(verified.length ? verified.map((v) => `- ${v}`) : [task.status === 'pending' ? '- To be defined with the acceptance criteria.' : '- Not recorded in the plan notes.']),
    '',
    '## Notes',
    '',
    task.notes ? sentence(task.notes) : 'None.',
    '',
    'Source records: `tasks.md`' + (scope ? ', `expanded-scope.md`' : '') + (review ? ', `browser-review.md`' : '') + (changes.length ? ', `changes.md`' : '') + '.',
    '',
  ].join('\n');
  return { intent, spec };
}

export function allTaskDocs(root = plan) {
  const read = (f: string) => (existsSync(join(root, f)) ? readFileSync(join(root, f), 'utf8') : '');
  const tasks = parseTasks(read('tasks.md'));
  const scope = parseScope(read('expanded-scope.md'));
  const review = parseReview(read('browser-review.md'));
  const changes = parseChanges(read('changes.md'));
  return tasks.map((t) => ({ task: t, ...taskDocs(t, scope.get(t.id), review.get(t.id), changes.get(t.id)) }));
}

function main() {
  const stale: string[] = [];
  let written = 0,
    kept = 0;
  for (const { task, intent, spec } of allTaskDocs()) {
    const dir = join(plan, 'tasks', task.id);
    for (const [file, content] of [
      ['intent.md', intent],
      ['spec.md', spec],
    ] as const) {
      const path = join(dir, file);
      const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
      if (current !== null && !current.startsWith(marker)) {
        kept++;
        continue;
      }
      if (current === content) continue;
      if (check) stale.push(path);
      else {
        mkdirSync(dir, { recursive: true });
        writeFileSync(path, content);
        written++;
      }
    }
  }
  if (check) {
    if (stale.length) {
      console.error(`Task documents are out of date (run pnpm plan:tasks):\n${stale.slice(0, 20).join('\n')}`);
      process.exit(1);
    }
    console.log('Task documents are up to date.');
  } else console.log(`${written} task documents written, ${kept} hand-edited kept.`);
}

if (process.argv[1]?.endsWith('plan-task-docs.ts')) main();
