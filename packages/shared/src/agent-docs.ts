import type { Item, Spec } from './schema';
import { stripAnswerMarkers } from './markdown';
import { modules } from './templates';
import { readiness } from './domain';

/**
 * Root documents that people and AI tools read first, generated from the specification:
 *  - PRODUCT.md — what and why (product requirements: problem, users, goals, scope, requirements).
 *  - DESIGN.md — how (a Google-style design document: context and scope, goals and non-goals,
 *    the design, alternatives considered, cross-cutting concerns) plus the visual design system
 *    that UI-generating agents need.
 * Like AGENTS.md (agents.md), they live at the repository root under a predictable name.
 */
const lang = (spec: Spec) => spec.language;
const t = (spec: Spec, en: string, fr: string) => (lang(spec) === 'fr' ? fr : en);
const section = (spec: Spec, id: string) => {
  const s = spec.sections.find((x) => x.id === id);
  // Drop the section's own H1 and demote headings by one level to nest under ours.
  return s ? [stripAnswerMarkers(s.markdown).replace(/^# .*\n+/, '').replace(/^(#{1,5}) /gm, '$1# ').trim(), s.diagram ? `\n\n\`\`\`mermaid\n${s.diagram}\n\`\`\`` : ''].join('') : '';
};
const title = (id: string, spec: Spec) => modules.find((m) => m.id === id)?.title[lang(spec)] ?? id;
const items = (spec: Spec, type: Item['type']) => spec.items.filter((i) => i.type === type && i.status !== 'superseded');
const header = (spec: Spec, doc: string) =>
  `# ${spec.name} — ${doc}\n\n> ${t(spec, 'Generated by SDD Studio from specification revision', 'Généré par SDD Studio depuis la révision')} ${spec.revision}. ${t(spec, 'Edit the specification, not this file; changes come back as proposals.', 'Modifiez la spécification, pas ce fichier ; les changements reviennent en propositions.')}\n`;
const block = (heading: string, body: string, empty: string) => `\n## ${heading}\n\n${body.trim() || `_${empty}_`}\n`;

export function productMarkdown(spec: Spec): string {
  const none = t(spec, 'Not recorded yet.', 'Pas encore consigné.');
  const requirements = items(spec, 'requirement')
    .map((r) => `| ${r.id} | ${r.title.replace(/\|/g, '\\|')} | ${r.priority ?? '—'} | ${(r.acceptance || '—').replace(/\n+/g, ' ').replace(/\|/g, '\\|')} |`)
    .join('\n');
  const useCases = items(spec, 'use-case')
    .map((u) => `### ${u.id}: ${u.title}\n\n${u.body.trim() || none}`)
    .join('\n\n');
  return [
    header(spec, t(spec, 'Product', 'Produit')),
    spec.description ? `\n${spec.description}\n` : '',
    block(t(spec, 'Problem, goals and stakeholders', 'Problème, objectifs et parties prenantes'), section(spec, 'discovery'), none),
    block(t(spec, 'Scope and non-goals', 'Portée et hors portée'), section(spec, 'scope'), none),
    block(t(spec, 'Users and workflows', 'Utilisateurs et parcours'), section(spec, 'workflows'), none),
    block(
      t(spec, 'Requirements', 'Exigences'),
      requirements ? `| ID | ${t(spec, 'Requirement', 'Exigence')} | ${t(spec, 'Priority', 'Priorité')} | ${t(spec, 'Acceptance', 'Acceptation')} |\n| --- | --- | --- | --- |\n${requirements}` : '',
      none,
    ),
    block(t(spec, 'Use cases', 'Cas d’utilisation'), useCases, none),
    block(t(spec, 'Quality attributes', 'Qualités attendues'), section(spec, 'quality'), none),
    block(t(spec, 'Release and governance', 'Livraison et gouvernance'), section(spec, 'governance'), none),
  ].join('');
}

/** `crossReferences: false` leaves out the pointer to PRODUCT.md, for a file that is read on its own inside a skill. */
export function designMarkdown(spec: Spec, options: { crossReferences?: boolean } = {}): string {
  const none = t(spec, 'Not recorded yet.', 'Pas encore consigné.');
  const r = readiness(spec);
  const decisions = items(spec, 'decision')
    .map((d) => `### ${d.id}: ${d.title}\n\n${t(spec, 'Status', 'Statut')}: ${d.status}\n\n${d.body.trim() || none}`)
    .join('\n\n');
  const components = items(spec, 'component')
    .map((c) => `- **${c.id} ${c.title}** — ${c.body.replace(/\n+/g, ' ').slice(0, 300) || none}`)
    .join('\n');
  const risks = items(spec, 'risk')
    .map((c) => `- **${c.id} ${c.title}** — ${c.body.replace(/\n+/g, ' ').slice(0, 300) || none}`)
    .join('\n');
  return [
    header(spec, t(spec, 'Design', 'Conception')),
    block(
      t(spec, 'Context and scope', 'Contexte et portée'),
      options.crossReferences === false
        ? spec.description
        : `${spec.description}\n\n${t(spec, 'See PRODUCT.md for the problem, users and requirements.', 'Voir PRODUCT.md pour le problème, les utilisateurs et les exigences.')}`,
      none,
    ),
    block(t(spec, 'Goals and non-goals', 'Objectifs et non-objectifs'), section(spec, 'scope'), none),
    block(t(spec, 'Design overview', 'Vue d’ensemble'), [section(spec, 'architecture'), components ? `### ${t(spec, 'Components', 'Composants')}\n\n${components}` : ''].filter(Boolean).join('\n\n'), none),
    block(title('data', spec), section(spec, 'data'), none),
    block(t(spec, 'Alternatives considered (decisions)', 'Options étudiées (décisions)'), decisions, none),
    block(
      t(spec, 'Cross-cutting concerns', 'Préoccupations transversales'),
      ['security', 'operations', 'testing', 'delivery', 'conventions']
        .map((id) => {
          const body = section(spec, id);
          return body ? `### ${title(id, spec)}\n\n${body.replace(/^(#{3,6}) /gm, '#$1 ')}` : '';
        })
        .filter(Boolean)
        .join('\n\n'),
      none,
    ),
    block(t(spec, 'Risks', 'Risques'), risks, none),
    block(t(spec, 'Visual design system (for UI agents)', 'Système visuel (pour les agents d’interface)'), section(spec, 'design'), none),
    block(
      t(spec, 'Open questions', 'Questions ouvertes'),
      r.blockers.map((b) => `- ${b}`).join('\n'),
      t(spec, 'None: the specification is ready for a baseline.', 'Aucune : la spécification est prête pour une référence.'),
    ),
  ].join('');
}
