describe('overview image', () => {
  const input = {
    name: 'Payments <API>',
    subtitle: 'Web application · r4',
    language: 'en' as const,
    readiness: 72,
    ready: false,
    completeness: 64,
    modules: Array.from({ length: 14 }, (_, i) => ({ title: `Module ${i + 1}`, done: i, total: 13 })),
    stack: ['React', 'PostgreSQL', 'Kubernetes'],
  };
  it('renders an accessible, escaped 1200×630 SVG', () => {
    const svg = overviewSvg(input);
    expect(svg).toMatch(/^<svg xmlns="http:\/\/www.w3.org\/2000\/svg" width="1200" height="630"/);
    expect(svg).toContain('role="img"');
    expect(svg).toContain('<title id="title">Payments &lt;API&gt;</title>');
    expect(svg).toContain('Readiness 72%, completeness 64%');
    expect(svg).toContain('>React<');
    expect(svg.match(/Module \d+/g)).toHaveLength(14);
    expect(svg).not.toMatch(/<script|href=/i);
  });
  it('clamps values and speaks French', () => {
    const svg = overviewSvg({ ...input, language: 'fr', readiness: 140, completeness: -5, stack: [], ready: true });
    expect(svg).toContain('>100%<');
    expect(svg).toContain('>0%<');
    expect(svg).toContain('Prêt pour une référence');
    expect(svg).toContain('Aucune technologie choisie');
  });
});

describe('Spec Kit workflow and export', () => {
  it('marks the first unfinished phase as active', () => {
    const status = phaseStatuses(createSpec('p1', 'Empty'));
    expect(Object.keys(status)).toEqual(sddPhases.map((p) => p.id));
    expect(Object.values(status).filter((s) => s === 'active')).toHaveLength(1);
    expect(status.constitution).toBe('active');
    expect(status.converge).toBe('todo');
  });
  it('writes the Spec Kit layout from the example specification', () => {
    const spec = buildExampleSpec('00000000-0000-4000-8000-000000000001');
    const files = specKitFiles(spec, ['React', 'PostgreSQL']);
    const feature = Object.keys(files).find((f) => f.endsWith('/spec.md'))!;
    expect(feature).toMatch(/^specs\/001-[\w-]+\/spec\.md$/);
    const dir = feature.replace('/spec.md', '');
    expect(Object.keys(files)).toEqual(
      expect.arrayContaining(['.specify/memory/constitution.md', `${dir}/plan.md`, `${dir}/research.md`, `${dir}/tasks.md`, `${dir}/checklists/requirements.md`]),
    );
    expect(files[feature]).toContain('## User Scenarios & Testing');
    expect(files[feature]).toMatch(/\*\*REQ-\d+\*\*/);
    expect(files[`${dir}/plan.md`]).toContain('- React');
    expect(files[`${dir}/tasks.md`]).toMatch(/- \[ \] T001 /);
    expect(files[`${dir}/tasks.md`]).toContain('[P] Configure PostgreSQL');
    expect(files[`${dir}/checklists/requirements.md`]).toMatch(/- \[[ x]\] .+ — \d+\/\d+/);
    expect(files['specs/roadmap.md']).toBeUndefined();
  });
  it('adds a roadmap when the project decomposes into sub-specifications', () => {
    const spec = buildExampleSpec('00000000-0000-4000-8000-000000000001');
    spec.sections.find((s) => s.id === 'governance')!.answers['governance.13'] = {
      value: 'Roadmap of sub-specifications (spec of specs)',
      state: 'answered',
      reason: '',
    } as any;
    const roadmap = specKitFiles(spec)['specs/roadmap.md'];
    expect(roadmap).toContain('| ID | Sub-feature | Intent | Scope boundary | Depends on | Status | Sub-spec |');
    expect(roadmap).toMatch(/\| UC-\d+ \|/);
  });
  it('classifies feature effects', () => {
    expect(featureEffect('gitPublishing')).toBe('read-write');
    expect(featureEffect('starter')).toBe('read-only');
  });
});

let h: Harness;
describe('export routes', () => {
  beforeAll(async () => {
    h = await setupApp('exports');
  });
  afterAll(async () => h?.teardown());

  it('serves LaTeX, HTML and SVG as inert attachments', async () => {
    const p = await h.createProject({ sample: true, name: 'Export sample' });
    const latex = await h.request('GET', `/projects/${p.id}/export/latex`);
    expect(latex.statusCode).toBe(200);
    expect(latex.headers['content-disposition']).toMatch(/attachment; filename="export-sample-r\d+\.tex"/);
    expect(latex.body).toContain('\\begin{longtable}');
    expect(latex.body).toContain('\\chapter{');
    const html = await h.request('GET', `/projects/${p.id}/export/html`);
    expect(html.headers['content-type']).toMatch(/^text\/html/);
    expect(html.headers['content-security-policy']).toBe("default-src 'none'; style-src 'unsafe-inline'; img-src data:");
    expect(html.body).toContain('<h1>Export sample</h1>');
    const svg = await h.request('GET', `/projects/${p.id}/export/svg`);
    expect(svg.headers['content-type']).toMatch(/^image\/svg\+xml/);
    expect(svg.headers['content-security-policy']).toContain("default-src 'none'");
    expect(svg.body).toContain('<svg');
  });
  it('serves a Spec Kit zip', async () => {
    const p = await h.createProject({ sample: true, name: 'Kit' });
    const res = await h.request('GET', `/projects/${p.id}/export/speckit`);
    expect(res.headers['content-type']).toBe('application/zip');
    expect(res.headers['content-disposition']).toMatch(/\.speckit\.zip"/);
    const zip = await JSZip.loadAsync(res.rawPayload);
    expect(Object.keys(zip.files)).toContain('.specify/memory/constitution.md');
  });
  it('refuses a PDF without a configured publisher and rejects unknown formats', async () => {
    const p = await h.createProject();
    const url = process.env.PUBLISHER_URL;
    delete process.env.PUBLISHER_URL;
    try {
      expect((await h.request('GET', `/projects/${p.id}/export/pdf`)).statusCode).toBe(503);
    } finally {
      if (url) process.env.PUBLISHER_URL = url;
    }
    expect((await h.request('GET', `/projects/${p.id}/export/docx`)).statusCode).toBe(400);
  });
  it('lets a viewer export but not an outsider', async () => {
    const p = await h.createProject();
    const viewer = await h.userWith('Viewer', { projectId: p.id, role: 'Viewer' });
    expect((await h.request('GET', `/projects/${p.id}/export/html`, undefined, viewer.cookie)).statusCode).toBe(200);
    const outsider = await h.userWith('Editor');
    expect((await h.request('GET', `/projects/${p.id}/export/html`, undefined, outsider.cookie)).statusCode).toBe(403);
  });
});
